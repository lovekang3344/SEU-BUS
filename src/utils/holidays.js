/**
 * 判断给定日期是否为节假日模式（即使用节假日时刻表）
 * @param {Date} date
 * @returns {'workday' | 'holiday'}
 */
export function getDayType(date) {
  const year = date.getFullYear()
  const month = String(date.getMonth() + 1).padStart(2, '0')
  const day = String(date.getDate()).padStart(2, '0')
  const key = `${month}-${day}`
  const yearData = HOLIDAY_CALENDAR[year]

  if (yearData) {
    if (yearData.workdays.includes(key)) return 'workday'
    if (yearData.holidays.includes(key)) return 'holiday'
  }

  // 不在日历中的日期，按周末判断
  const dow = date.getDay()
  return dow === 0 || dow === 6 ? 'holiday' : 'workday'
}

